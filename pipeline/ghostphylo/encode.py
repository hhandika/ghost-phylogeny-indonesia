"""Step 2: encode the taxa as a morphological character matrix (Nexus + PHYLIP).

Characters 1-18 are the source's coded traits (states 0/1/2). Character 19
is the body plan and 20 the diet, each one unordered multistate character, so
a body plan counts once rather than as many one-hot columns. Clade is left out
on purpose: it is the classification the tree is meant to test.
"""

from __future__ import annotations

import csv

from . import config as C

SYMBOLS = "0123456789ABCDEFGHIJKLMNOPQRSTUV"


def characters() -> list[dict]:
    chars = [{"id": t["id"], "label": t["label"], "states": t["states"]} for t in C.TRAITS]
    chars.append({"id": "body_plan", "label": "Body plan", "states": [label for _, label in C.BODY_PLANS]})
    chars.append({"id": "diet", "label": "Diet", "states": C.DIETS})
    return chars


def rows(taxa: list[dict]) -> dict[str, str]:
    plans = [k for k, _ in C.BODY_PLANS]
    out = {}
    for t in taxa:
        cells = ["?" if t["traits"][c["id"]] is None else SYMBOLS[t["traits"][c["id"]]] for c in C.TRAITS]
        cells.append(SYMBOLS[plans.index(t["bodyPlan"])])
        cells.append("?" if t["dietClass"] is None else SYMBOLS[C.DIETS.index(t["dietClass"])])
        out[t["id"]] = "".join(cells)
    return out


def _quote(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def run(taxa: list[dict]) -> dict[str, str]:
    chars = characters()
    matrix = rows(taxa)
    nstates = max(len(c["states"]) for c in chars)
    width = max(len(k) for k in matrix) + 2

    labels = ",\n".join(
        f"    {i} {c['id']} / {' '.join(_quote(s) for s in c['states'])}" for i, c in enumerate(chars, 1)
    )
    body = "\n".join(f"    {k.ljust(width)}{v}" for k, v in matrix.items())
    nexus = f"""#NEXUS
[Generated by ghostphylo.encode from {C.SOURCE_CSV.name}. Do not edit by hand.]

BEGIN DATA;
  DIMENSIONS NTAX={len(matrix)} NCHAR={len(chars)};
  FORMAT DATATYPE=STANDARD MISSING=? GAP=- SYMBOLS="{' '.join(SYMBOLS[:nstates])}";
  CHARSTATELABELS
{labels}
  ;
  MATRIX
{body}
  ;
END;
"""
    C.PROCESSED.mkdir(parents=True, exist_ok=True)
    (C.PROCESSED / f"{C.PREFIX}.nex").write_text(nexus)
    phy = f"{len(matrix)} {len(chars)}\n" + "\n".join(f"{k.ljust(width)}{v}" for k, v in matrix.items()) + "\n"
    (C.PROCESSED / f"{C.PREFIX}.phy").write_text(phy)
    with open(C.PROCESSED / "characters.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["number", "id", "label", "states"])
        for i, c in enumerate(chars, 1):
            w.writerow([i, c["id"], c["label"], "; ".join(f"{SYMBOLS[j]} {s}" for j, s in enumerate(c["states"]))])

    # Taxa with identical rows cannot be told apart by any tree.
    groups: dict[str, list[str]] = {}
    for k, v in matrix.items():
        groups.setdefault(v, []).append(k)
    ties = sum(1 for g in groups.values() if len(g) > 1)
    print(f"encode: {len(matrix)} taxa x {len(chars)} characters, {len(groups)} unique rows ({ties} shared) -> {C.PREFIX}.nex")
    return matrix
